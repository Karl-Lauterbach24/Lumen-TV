#!/usr/bin/env python3
"""Writes the Android string resources from the texts of the web receiver, so all TV apps
say the same thing in the same languages.

    python tools/gen_android_strings.py --lumen <Lumen checkout>

Source: the STR table in receiver/receiver.js of the Lumen repository.
Result: android/app/src/main/res/values[-<language>]/strings.xml
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KEYS = {
    "searching": "searching", "notFound": "not_found", "enter": "enter", "connect": "connect",
    "search": "search", "connecting": "connecting", "ready": "ready", "choose": "choose",
    "disconnect": "disconnect", "lost": "lost", "failed": "failed",
}


def xml(text):
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    return text.replace("%1", "%1$s")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lumen", required=True)
    a = ap.parse_args()
    with open(os.path.join(a.lumen, "receiver", "receiver.js"), encoding="utf-8") as f:
        source = f.read()
    table = source[source.index("var STR = {"):source.index("var lang =")]
    languages = re.findall(r"^    (\w\w): \{(.*?)\}[,\n]", table, re.S | re.M)
    if len(languages) < 2:
        sys.exit("could not read the STR table from receiver.js")
    for code, body in languages:
        entries = dict(re.findall(r"(\w+): '((?:[^'\\]|\\.)*)'", body))
        missing = [k for k in KEYS if k not in entries]
        if missing:
            sys.exit("%s: missing %s" % (code, ", ".join(missing)))
        folder = os.path.join(HERE, "android", "app", "src", "main", "res", "values" if code == "en" else "values-" + code)
        os.makedirs(folder, exist_ok=True)
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- Generated by tools/gen_android_strings.py from Lumen's receiver/receiver.js. Do not edit. -->",
                 "<resources>"]
        if code == "en":
            lines.append('    <string name="app_name" translatable="false">Lumen TV</string>')
        for js, android in KEYS.items():
            lines.append('    <string name="%s">%s</string>' % (android, xml(entries[js])))
        lines.append("</resources>")
        with open(os.path.join(folder, "strings.xml"), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")
        print(code, len(KEYS))


if __name__ == "__main__":
    main()
